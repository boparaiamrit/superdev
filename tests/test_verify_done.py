def routes_js(*routes: tuple[str, str, str], before: str = "", after: str = "", exit_code: int = 0, stderr: str = "") -> str:
    """What `<binary> routes --json` prints: the routes as Navree lists them, between optional log lines."""
    listed = [{"method": m, "path": p, "name": None, "access": a, "module": "app", "page": False} for m, p, a in routes]
    body = before + json.dumps(listed, indent=2) + "\n" + after
    return f"process.stdout.write({json.dumps(body)});\nprocess.stderr.write({json.dumps(stderr)});\nprocess.exit({exit_code});\n"


